def _build_trig_circle_code(cfg: dict) -> str:
    code = '''from manimlib import *
import numpy as np

class GeneratedMathScene(Scene):
    """
    Unit Circle Trigonometric Wave Generation
    Generated by MathMotion Studio
    """
    def construct(self):
        title = Title(r"Trigonometry: Unwinding the Sine Wave")
        title.set_color_by_gradient(CYAN, BLUE)
        self.play(Write(title))
        
        # Unit Circle on the left
        circle_center = LEFT * 3.5 + DOWN * 0.5
        radius = 1.8
        circle = Circle(radius=radius, color=BLUE, stroke_width=3).move_to(circle_center)
        axes_circle = Axes(x_range=[-1.5, 1.5, 1], y_range=[-1.5, 1.5, 1], width=4, height=4).move_to(circle_center)
        
        # Wave Axes on the right
        axes_wave = Axes(
            x_range=[0, 3 * PI, PI],
            y_range=[-1.5, 1.5, 1],
            width=6.5,
            height=4
        ).move_to(RIGHT * 2.5 + DOWN * 0.5)
        
        self.play(ShowCreation(circle), ShowCreation(axes_circle), ShowCreation(axes_wave))
        
        # Angle tracker
        theta = ValueTracker(0)
        
        # Rotating radius and projecting line
        def get_dot():
            ang = theta.get_value()
            return circle_center + np.array([radius * np.cos(ang), radius * np.sin(ang), 0])
            
        dot = always_redraw(lambda: Dot(get_dot(), color=YELLOW, radius=0.08))
        radius_line = always_redraw(lambda: Line(circle_center, get_dot(), color=YELLOW, stroke_width=2.5))
        
        # Projected horizontal line
        proj_line = always_redraw(lambda: DashedLine(
            get_dot(),
            axes_wave.c2p(theta.get_value(), np.sin(theta.get_value())),
            color=RED_B,
            stroke_width=1.5
        ))
        
        # Sine wave trace
        sine_curve = always_redraw(lambda: axes_wave.get_graph(
            lambda x: np.sin(x),
            x_range=[0, max(0.01, theta.get_value())],
            color=RED
        ))
        
        self.add(dot, radius_line, proj_line, sine_curve)
        self.play(theta.animate.set_value(2.5 * PI), run_time=6, rate_func=linear)
        self.wait(1)
'''
    return code


def _build_latex_proof_code(cfg: dict) -> str:
    steps = cfg.get("steps", [
        r"e^{i\theta} = \cos(\theta) + i\sin(\theta)",
        r"\text{Let } \theta = \pi",
        r"e^{i\pi} = \cos(\pi) + i\sin(\pi)",
        r"e^{i\pi} = -1 + 0",
        r"e^{i\pi} + 1 = 0"
    ])
    
    steps_repr = repr(steps)
    
    code = f'''from manimlib import *

class GeneratedMathScene(Scene):
    """
    Step-by-Step Mathematical Proof
    Generated by MathMotion Studio
    """
    def construct(self):
        title = Title(r"Step-by-Step Mathematical Morphing")
        title.set_color_by_gradient(GOLD_C, YELLOW_A)
        self.play(Write(title))
        
        proof_steps = {steps_repr}
        
        current_tex = Tex(proof_steps[0], font_size=44, color=WHITE).center()
        self.play(Write(current_tex), run_time=1.5)
        self.wait(0.8)
        
        for next_step_str in proof_steps[1:]:
            next_tex = Tex(next_step_str, font_size=44, color=YELLOW).center()
            self.play(TransformMatchingTex(current_tex, next_tex), run_time=1.5)
            current_tex = next_tex
            self.wait(0.8)
            
        box = SurroundingRectangle(current_tex, color=GOLD, buff=0.25)
        self.play(ShowCreation(box))
        self.wait(1.5)
'''
    return code


def _build_storyboard_code(cfg: dict) -> str:
    beats = cfg.get("beats", [])
    
    code = '''from manimlib import *
import numpy as np

class GeneratedMathScene(Scene):
    """
    Custom Storyboard Mathematical Scene
    Generated by MathMotion Studio
    """
    def construct(self):
'''
    if not beats:
        code += '''        title = Title("MathMotion Storyboard")
        self.play(Write(title))
        circle = Circle(color=BLUE, radius=2)
        self.play(ShowCreation(circle))
        self.wait(1)
'''
        return code

    for idx, beat in enumerate(beats):
        b_type = beat.get("type", "write_title")
        dur = float(beat.get("duration", 1.0))
        
        if b_type == "title":
            txt = beat.get("text", "Mathematical Concept")
            code += f'''        # Beat {idx+1}: Title
        t_{idx} = Title(r"{txt}")
        self.play(Write(t_{idx}), run_time={dur})
'''
        elif b_type == "formula":
            f_str = beat.get("latex", "f(x) = x^2")
            pos = beat.get("position", "center")
            code += f'''        # Beat {idx+1}: Formula
        tex_{idx} = Tex(r"{f_str}", font_size=40).{pos}()
        self.play(Write(tex_{idx}), run_time={dur})
'''
        elif b_type == "graph":
            func = beat.get("function", "np.sin(x)")
            code += f'''        # Beat {idx+1}: Axes and Function
        ax_{idx} = Axes(x_range=[-4, 4, 1], y_range=[-2, 2, 1], width=8, height=4.5)
        g_{idx} = ax_{idx}.get_graph(lambda x: {func}, color=YELLOW)
        self.play(ShowCreation(ax_{idx}), ShowCreation(g_{idx}), run_time={dur})
'''
        elif b_type == "wait":
            code += f'''        # Beat {idx+1}: Pause
        self.wait({dur})
'''
    code += '        self.wait(1)\n'
    return code



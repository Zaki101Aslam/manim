class GeneratedMathScene(Scene):
    """
    Fourier Epicycles Series
    Generated by MathMotion Studio
    """
    def construct(self):
        title = Title(r"Fourier Epicycles: Drawing with Rotating Circles")
        title.set_color_by_gradient(PURPLE_B, PINK)
        self.play(Write(title))
        
        # Epicycles concept
        circle_group = VGroup()
        center = np.array([0, 0, 0])
        
        radii = [1.5 / (k + 1) for k in range({n_circles})]
